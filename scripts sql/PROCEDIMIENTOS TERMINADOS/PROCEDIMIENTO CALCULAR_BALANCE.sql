CREATE PROCEDURE CALCULAR_BALANCE(JUEGO INT, NOMBRE_COMPANIA VARCHAR(15))
BEGIN
	DECLARE DUMMY_ID, COSTO_UBICACION, COSTO_TIPO_BARCO, COSTO_VALOR, NO_MORE_DATA, COSTO_OPERATIVO INT DEFAULT 0;
	DECLARE COSTO_COSTA_CHALUPA, COSTO_COSTA_BARCO, COSTO_COSTA_PANGA, COSTO_PUERTO_BARCO, COSTO_PUERTO_PANGA, COSTO_PUERTO_CHALUPA, COSTO_MAR_PANGA, COSTO_MAR_BARCO, COSTO_MAR_CHALUPA INT DEFAULT 0;
	DECLARE CANTIDAD, UBICACION, TIPO INT DEFAULT 0;
	DECLARE CURSOR_COSTOS_OPERATIVOS CURSOR FOR
										SELECT * 
										FROM COSTOSXUBICACIONXTIPO;
	DECLARE BARCOS CURSOR FOR
						SELECT CANTIDAD_BARCOS, UBICACION_ID, TIPO_BARCO_ID
						FROM   BARCOSXCOMPANIA
						WHERE  JUEGO_ID = JUEGO AND COMPANIA_NOMBRE = NOMBRE_COMPANIA;
	DECLARE CONTINUE HANDLER FOR NOT FOUND
		SET NO_MORE_DATA = 1;
	OPEN CURSOR_COSTOS_OPERATIVOS;
	FETCH CURSOR_COSTOS_OPERATIVOS INTO DUMMY_ID, COSTO_UBICACION, COSTO_TIPO_BARCO, COSTO_VALOR;
	WHILE NO_MORE_DATA = 0 DO
		CASE COSTO_UBICACION
			WHEN 0 THEN
				CASE COSTO_TIPO_BARCO
					WHEN 1 THEN SET COSTO_PUERTO_CHALUPA = COSTO_VALOR;
					WHEN 2 THEN SET COSTO_PUERTO_PANGA   = COSTO_VALOR;
					WHEN 3 THEN SET COSTO_PUERTO_BARCO   = COSTO_VALOR;
				END CASE;
			WHEN 1 THEN
				CASE COSTO_TIPO_BARCO
					WHEN 1 THEN SET COSTO_COSTA_CHALUPA = COSTO_VALOR;
					WHEN 2 THEN SET COSTO_COSTA_PANGA   = COSTO_VALOR;
					WHEN 3 THEN SET COSTO_COSTA_BARCO   = COSTO_VALOR;
				END CASE;
			WHEN 2 THEN
				CASE COSTO_TIPO_BARCO
					WHEN 1 THEN SET COSTO_MAR_CHALUPA = COSTO_VALOR;
					WHEN 2 THEN SET COSTO_MAR_PANGA   = COSTO_VALOR;
					WHEN 3 THEN SET COSTO_MAR_BARCO   = COSTO_VALOR;
				END CASE;
		END CASE;
		FETCH CURSOR_COSTOS_OPERATIVOS INTO DUMMY_ID, COSTO_UBICACION, COSTO_TIPO_BARCO, COSTO_VALOR;
	END WHILE;
	CLOSE CURSOR_COSTOS_OPERATIVOS;
	SET NO_MORE_DATA = 0;
	OPEN BARCOS;
	FETCH BARCOS INTO CANTIDAD, UBICACION, TIPO;
	WHILE NO_MORE_DATA = 0 DO -- SE RECORREN TODOS LOS BARCOS DE CADA COMPANIA
		CASE UBICACION
			WHEN 0 THEN
				CASE TIPO
					WHEN 1 THEN SET COSTO_OPERATIVO = COSTO_OPERATIVO+(CANTIDAD*COSTO_PUERTO_CHALUPA);
					WHEN 2 THEN SET COSTO_OPERATIVO = COSTO_OPERATIVO+(CANTIDAD*COSTO_PUERTO_PANGA);
					WHEN 3 THEN SET COSTO_OPERATIVO = COSTO_OPERATIVO+(CANTIDAD*COSTO_PUERTO_BARCO);
				END CASE;
			WHEN 1 THEN
				CASE TIPO
					WHEN 1 THEN SET COSTO_OPERATIVO = COSTO_OPERATIVO+(CANTIDAD*COSTO_COSTA_CHALUPA);
					WHEN 2 THEN SET COSTO_OPERATIVO = COSTO_OPERATIVO+(CANTIDAD*COSTO_COSTA_PANGA);
					WHEN 3 THEN SET COSTO_OPERATIVO = COSTO_OPERATIVO+(CANTIDAD*COSTO_COSTA_BARCO);
				END CASE;
			WHEN 2 THEN
				CASE TIPO
					WHEN 1 THEN SET COSTO_OPERATIVO = COSTO_OPERATIVO+(CANTIDAD*COSTO_MAR_CHALUPA);
					WHEN 2 THEN SET COSTO_OPERATIVO = COSTO_OPERATIVO+(CANTIDAD*COSTO_MAR_PANGA);
					WHEN 3 THEN SET COSTO_OPERATIVO = COSTO_OPERATIVO+(CANTIDAD*COSTO_MAR_BARCO);
				END CASE;
		END CASE;
		FETCH BARCOS INTO CANTIDAD, UBICACION, TIPO;
	END WHILE;
	CLOSE BARCOS;
	UPDATE COMPANIA SET COSTO_ULTIMO_TURNO = COSTO_OPERATIVO WHERE JUEGO_ID = JUEGO AND NOMBRE = NOMBRE_COMPANIA;
END $$