CREATE EVENT INSERTAR_TURNO ON SCHEDULE EVERY 1 MINUTE STARTS NOW()+INTERVAL 1 MINUTE ENDS NOW()+INTERVAL 10 MINUTE DO -- RECORDAR QUE EL NOMBRE SERA DE ACUERDO AL JUEGO
BEGIN
	DECLARE TURNO_ACTUAL INT DEFAULT 0;
	SELECT GET_TURNO(1) INTO TURNO_ACTUAL;-- EN VEZ DE 1 SE DEBERA COLOCAR LA VARIABLE DEL JUEGO VIA PHP
	IF TURNO_ACTUAL = 12 THEN
		DROP EVENT INSERTAR_TURNO;
		UPDATE JUEGO SET FINALIZADO = TRUE WHERE JUEGO_ID = 1;
	ELSEIF 
		INSERT INTO TURNO VALUES(TURNO_ACTUAL+1, 1);-- EN VEZ DE 1 SE DEBERA COLOCAR LA VARIABLE DEL JUEGO VIA PHP
	END IF;
END$$