CREATE PROCEDURE REPRODUCIR_PECES(TURNO_ID INT, JUEGO_ID INT)
BEGIN
	CALL ACTUALIZAR_POBLACION_ROBALO_COSTA(TURNO_ID, JUEGO_ID);
	CALL ACTUALIZAR_POBLACION_ROBALO_MAR_PROFUNDO(TURNO_ID, JUEGO_ID);
	CALL ACTUALIZAR_POBLACION_SIERRA_COSTA(TURNO_ID, JUEGO_ID);
	CALL ACTUALIZAR_POBLACION_SIERRA_MAR_PROFUNDO(TURNO_ID, JUEGO_ID);
	CALL ACTUALIZAR_POBLACION_PARGO_COSTA(TURNO_ID, JUEGO_ID);
	CALL ACTUALIZAR_POBLACION_PARGO_MAR_PROFUNDO(TURNO_ID, JUEGO_ID);
END $$