DROP PROCEDURE IF EXISTS ASIGNAR_BARCOS_SUBASTA;
CREATE PROCEDURE ASIGNAR_BARCOS_SUBASTA(TURNO INT, JUEGO INT) 
BEGIN
	DECLARE NO_MORE_DATA, VALOR_SUBASTA, VALOR_OFERTA INT DEFAULT 0;
	DECLARE NOMBRE_COMPANIA VARCHAR(15);
	DECLARE CURSOR_VALOR_SUBASTA CURSOR FOR
				SELECT COSTO
				FROM   SUBASTA
				WHERE  JUEGO_ID = JUEGO AND TURNO_ID = TURNO-1;
	DECLARE CURSOR_COMPANIA_MAYOR_OFERTA CURSOR FOR 
				SELECT   COMPANIA_NOMBRE, MAX( VALOR ) 
				FROM     OFERTA
				WHERE    TURNO_ID = TURNO-1 AND JUEGO_ID = JUEGO
                GROUP BY COMPANIA_NOMBRE
                ORDER BY  VALOR DESC 
				LIMIT 1;
	DECLARE  CONTINUE HANDLER FOR NOT FOUND 
		SET  NO_MORE_DATA = 1;
	OPEN CURSOR_VALOR_SUBASTA;
	OPEN CURSOR_COMPANIA_MAYOR_OFERTA;
	FETCH CURSOR_COMPANIA_MAYOR_OFERTA INTO NOMBRE_COMPANIA, VALOR_OFERTA;
	FETCH CURSOR_VALOR_SUBASTA INTO VALOR_SUBASTA;
	WHILE NO_MORE_DATA = 0 DO
		IF VALOR_OFERTA >= VALOR_SUBASTA THEN
			CALL INSERTAR_CHALUPAS_SUBASTA(NOMBRE_COMPANIA,JUEGO,TURNO);
			CALL INSERTAR_PANGAS_SUBASTA(NOMBRE_COMPANIA,JUEGO,TURNO);
			CALL INSERTAR_PESQUEROS_SUBASTA(NOMBRE_COMPANIA,JUEGO,TURNO);
			UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL - VALOR_OFERTA WHERE JUEGO_ID = JUEGO AND COMPANIA_NOMBRE = NOMBRE_COMPANIA AND TURNO_ID = TURNO;
		END IF;
		FETCH CURSOR_COMPANIA_MAYOR_OFERTA INTO NOMBRE_COMPANIA, VALOR_OFERTA;
		FETCH CURSOR_VALOR_SUBASTA INTO VALOR_SUBASTA;
	END WHILE;
	CLOSE CURSOR_VALOR_SUBASTA;
	CLOSE CURSOR_COMPANIA_MAYOR_OFERTA;
END $$