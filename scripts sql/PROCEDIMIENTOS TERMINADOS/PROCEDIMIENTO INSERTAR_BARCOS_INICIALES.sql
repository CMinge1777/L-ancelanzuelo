DROP PROCEDURE IF EXISTS INSERTAR_BARCOS_INICIALES;
CREATE PROCEDURE INSERTAR_BARCOS_INICIALES(JUEGO INT)
BEGIN
   DECLARE NOMBRE_COMPANIA VARCHAR(15);
   DECLARE CONTADOR_TIPOS_BARCO, NO_MORE_DATA, CONTADOR_BARCOS, CHALUPAS, PANGAS, BARCOS INT DEFAULT 0; -- LLEVA CUENTA DE LOS TIPOS DE BARCOS A INSERTAR
   DECLARE CURSOR_BARCOS_INICIALES CURSOR FOR
							SELECT CHALUPAS_INICIALES, PANGAS_INICIALES, BARCOS_INICIALES
							FROM DATOS_INICIALES;
   DECLARE CURSOR_NOMBRES_COMPANIAS CURSOR FOR 
										SELECT NOMBRE 
										FROM   COMPANIA 
										WHERE  JUEGO_ID = JUEGO;
	DECLARE  CONTINUE HANDLER FOR NOT FOUND 
		SET  NO_MORE_DATA = 1;
	OPEN CURSOR_NOMBRES_COMPANIAS;
	OPEN CURSOR_BARCOS_INICIALES;
	FETCH CURSOR_BARCOS_INICIALES INTO CHALUPAS, PANGAS, BARCOS;
	WHILE NO_MORE_DATA = 0 DO
		FETCH CURSOR_NOMBRES_COMPANIAS INTO NOMBRE_COMPANIA;
		WHILE NO_MORE_DATA = 0 DO
			WHILE CONTADOR_TIPOS_BARCO < 3 DO
				CASE CONTADOR_TIPOS_BARCO
					WHEN 0 THEN 
						INSERT INTO BARCOSXCOMPANIA VALUES(CHALUPAS, 0, 1, NOMBRE_COMPANIA, JUEGO); -- DEPENDE DE CUANTOS BARCOS SE DEFINA
						INSERT INTO BARCOSXCOMPANIA VALUES(0, 1, 1, NOMBRE_COMPANIA, JUEGO); -- DEPENDE DE CUANTOS BARCOS SE DEFINA
						INSERT INTO BARCOSXCOMPANIA VALUES(0, 2, 1, NOMBRE_COMPANIA, JUEGO); -- DEPENDE DE CUANTOS BARCOS SE DEFINA
					WHEN 1 THEN 
						INSERT INTO BARCOSXCOMPANIA VALUES(PANGAS, 0, 2, NOMBRE_COMPANIA, JUEGO); -- DEPENDE DE CUANTOS BARCOS SE DEFINA
						INSERT INTO BARCOSXCOMPANIA VALUES(0, 1, 2, NOMBRE_COMPANIA, JUEGO); -- DEPENDE DE CUANTOS BARCOS SE DEFINA
						INSERT INTO BARCOSXCOMPANIA VALUES(0, 2, 2, NOMBRE_COMPANIA, JUEGO); -- DEPENDE DE CUANTOS BARCOS SE DEFINA
					WHEN 2 THEN 
						INSERT INTO BARCOSXCOMPANIA VALUES(BARCOS, 0, 3, NOMBRE_COMPANIA, JUEGO); -- DEPENDE DE CUANTOS BARCOS SE DEFINA
						INSERT INTO BARCOSXCOMPANIA VALUES(0, 1, 3, NOMBRE_COMPANIA, JUEGO); -- DEPENDE DE CUANTOS BARCOS SE DEFINA
						INSERT INTO BARCOSXCOMPANIA VALUES(0, 2, 3, NOMBRE_COMPANIA, JUEGO); -- DEPENDE DE CUANTOS BARCOS SE DEFINA
				END CASE;
				SET CONTADOR_TIPOS_BARCO = CONTADOR_TIPOS_BARCO + 1;
			END WHILE;
			FETCH CURSOR_NOMBRES_COMPANIAS INTO NOMBRE_COMPANIA;
			SET CONTADOR_TIPOS_BARCO = 0;
		END WHILE;
		CLOSE CURSOR_NOMBRES_COMPANIAS;
		FETCH CURSOR_BARCOS_INICIALES INTO CHALUPAS, PANGAS, BARCOS;
	END WHILE;
	CLOSE CURSOR_BARCOS_INICIALES;
END $$

