DROP PROCEDURE TURNO_FINALIZADO;
CREATE PROCEDURE TURNO_FINALIZADO(TURNO_ID INT, JUEGO INT)
BEGIN
	IF TURNO_ID = 0 THEN
		CALL ASIGNAR_POBLACION_INICIAL(JUEGO);		   -- LISTO
		CALL INSERTAR_BARCOS_INICIALES(JUEGO);		   -- LISTO
		CALL INSERTAR_REPORTE_BASE(TURNO_ID, JUEGO);	   -- LISTO
	ELSEIF TURNO_ID = 12 THEN 
		CALL INSERTAR_REPORTE_BASE(TURNO_ID, JUEGO);    -- LISTO
		CALL POSICIONAR_EMBARCACIONES(TURNO_ID, JUEGO); -- LISTO
		CALL COBRAR_COSTOS_OPERATIVOS(TURNO_ID, JUEGO); -- LISTO
		CALL REPRODUCIR_PECES(TURNO_ID, JUEGO);		   -- LISTO
		CALL ASIGNAR_BARCOS_SUBASTA(TURNO_ID, JUEGO);   -- LISTO
		CALL CALCULAR_CAPTURA(TURNO_ID, JUEGO);         -- LISTO
		CALL ASIGNAR_BARCOS_PEDIDOS(TURNO_ID, JUEGO);   -- LISTO
		CALL CALCULAR_BALANCES(JUEGO);
		UPDATE JUEGO SET FINALIZADO = 1 WHERE JUEGO_ID = JUEGO;
	ELSE
		CALL INSERTAR_REPORTE_BASE(TURNO_ID, JUEGO);    -- LISTO
		CALL POSICIONAR_EMBARCACIONES(TURNO_ID, JUEGO); -- LISTO
		CALL COBRAR_COSTOS_OPERATIVOS(TURNO_ID, JUEGO); -- LISTO
		CALL REPRODUCIR_PECES(TURNO_ID, JUEGO);		   -- LISTO
		CALL ASIGNAR_BARCOS_SUBASTA(TURNO_ID, JUEGO);   -- LISTO
		CALL CALCULAR_CAPTURA(TURNO_ID, JUEGO);         -- LISTO
		CALL ASIGNAR_BARCOS_PEDIDOS(TURNO_ID, JUEGO);   -- LISTO
		CALL CALCULAR_BALANCES(JUEGO);
	END IF;
END $$