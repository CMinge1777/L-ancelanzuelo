-- SIRVE PARA AGREGAR BARCOS QUE SALGAN DE PEDIDOS O SUBASTAS
DROP PROCEDURE IF EXISTS INSERTAR_BARCOS; 
CREATE PROCEDURE INSERTAR_BARCOS(NOMBRE VARCHAR(40), JUEGO INT, TIPO INT,CANTIDAD INT)
BEGIN
	DECLARE NUMERO_BARCOS,NO_MORE_DATA INT DEFAULT 0;
	DECLARE CURSOR_CANTIDAD_BARCOS CURSOR FOR 
									SELECT CANTIDAD_BARCOS
									FROM BARCOSXCOMPANIA
									WHERE JUEGO_ID = JUEGO AND COMPANIA_NOMBRE = NOMBRE AND UBICACION_ID = 0 AND TIPO_BARCO_ID = TIPO;
	DECLARE  CONTINUE HANDLER FOR NOT FOUND 
		SET  NO_MORE_DATA = 1;
	OPEN CURSOR_CANTIDAD_BARCOS;
	FETCH CURSOR_CANTIDAD_BARCOS INTO NUMERO_BARCOS;
	IF NO_MORE_DATA = 1 THEN -- SI NO EXISTEN BARCOS EN EL PUERTO ENTONCES SE REALIZA UNA INSERCION CON LA NUEVA CANTIDAD DE BARCOS QUE SE VAN A INSERTAR
		IF CANTIDAD > 0 THEN -- SE SE ENVIA NUMERO DE BARCOS IGUAL A CERO ENTONCES NO SE INSERTA NADA
			INSERT INTO BARCOSXCOMPANIA VALUES(CANTIDAD, 0, TIPO, NOMBRE, JUEGO);
		END IF;
	END IF;
	WHILE NO_MORE_DATA = 0 DO -- SI SI EXISTEN BARCOS DEL TIPO SUMINISTRADO UBICADOS EN PUERTO ENTONCES SE HACE UN UPDATE SOBRE LA CANTIDAD DE BARCOS EXISTENTES
		IF CANTIDAD > 0 THEN -- SE SE ENVIA NUMERO DE BARCOS IGUAL A CERO ENTONCES NO SE INSERTA NADA
			UPDATE BARCOSXCOMPANIA SET CANTIDAD_BARCOS = NUMERO_BARCOS + CANTIDAD WHERE JUEGO_ID = JUEGO AND COMPANIA_NOMBRE = NOMBRE AND UBICACION_ID = 0 AND TIPO_BARCO_ID = TIPO;
		END IF;
		FETCH CURSOR_CANTIDAD_BARCOS INTO NUMERO_BARCOS;
	END WHILE;
	CLOSE CURSOR_CANTIDAD_BARCOS;
END $$