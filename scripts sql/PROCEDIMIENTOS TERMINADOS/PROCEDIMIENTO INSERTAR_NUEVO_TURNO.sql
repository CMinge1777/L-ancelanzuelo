CREATE PROCEDURE INSERTAR_NUEVO_TURNO()
BEGIN
	DECLARE NO_MORE_DATA, JUEGO, TURNO, DURACION INT DEFAULT 0;
	DECLARE HORAS, MINUTOS, SEGUNDOS, DIAS, MESES INT DEFAULT 0;
	DECLARE FECHA_INSERCION,FECHA_INSERCION_NUEVO_TURNO, FECHA_ACTUAL DATETIME;
	DECLARE CURSOR_JUEGOS_ACTIVOS CURSOR FOR 
				SELECT `TURNO`.`TURNO_ID` AS `TURNO_ID`, `TURNO`.`INSERCION` AS `INSERCION`, `JUEGO`.`DURACION_TURNOS` AS `DURACION_TURNOS`, `TURNO`.`JUEGO_ID` AS `JUEGO_ID`
				FROM TURNO, JUEGO
				WHERE ((`TURNO`.`TURNO_ID`  = (SELECT MAX(`TURNO`.`TURNO_ID`) AS TURNO_ID FROM `TURNO` WHERE (`TURNO`.`JUEGO_ID` = `JUEGO`.`JUEGO_ID`))) AND (`JUEGO`.`FINALIZADO` = 0) AND (`JUEGO`.`JUEGO_ID` =`TURNO`.`JUEGO_ID`));
	DECLARE  CONTINUE HANDLER FOR NOT FOUND 
		SET  NO_MORE_DATA = 1;
	SET FECHA_ACTUAL = CURRENT_TIMESTAMP;
	OPEN CURSOR_JUEGOS_ACTIVOS;
	FETCH CURSOR_JUEGOS_ACTIVOS INTO TURNO, FECHA_INSERCION, DURACION, JUEGO;
	WHILE NO_MORE_DATA = 0 DO
		SET FECHA_INSERCION_NUEVO_TURNO = DATE_ADD(FECHA_INSERCION, INTERVAL DURACION MINUTE);
		IF FECHA_ACTUAL >= FECHA_INSERCION_NUEVO_TURNO THEN
			INSERT INTO TURNO VALUES(TURNO + 1, JUEGO, NOW());
			IF TURNO = 11 THEN
				UPDATE JUEGO SET FINALIZADO = TRUE WHERE JUEGO_ID = JUEGO;
			END IF;
		END IF;
	FETCH CURSOR_JUEGOS_ACTIVOS INTO TURNO, FECHA_INSERCION, DURACION, JUEGO;		
	END WHILE;
	CLOSE CURSOR_JUEGOS_ACTIVOS;
END $$