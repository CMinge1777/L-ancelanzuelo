DROP PROCEDURE IF EXISTS INSERTAR_REPORTE_BASE;
CREATE PROCEDURE INSERTAR_REPORTE_BASE(TURNO INT, JUEGO INT)
BEGIN
	DECLARE NOMBRE_COMPANIA VARCHAR(15);
	DECLARE NO_MORE_DATA, DINERO INT DEFAULT 0;
	DECLARE CURSOR_REPORTE_BASE CURSOR FOR
							SELECT DINERO_INICIAL
							FROM DATOS_INICIALES;
	DECLARE CURSOR_NOMBRES_COMPANIAS CURSOR FOR 
								SELECT NOMBRE
								FROM COMPANIA 
								WHERE JUEGO_ID = JUEGO;
	DECLARE CONTINUE HANDLER FOR NOT FOUND
		SET NO_MORE_DATA = 1;
	OPEN CURSOR_NOMBRES_COMPANIAS;
	OPEN CURSOR_REPORTE_BASE;
	FETCH CURSOR_REPORTE_BASE INTO DINERO;
	WHILE NO_MORE_DATA = 0 DO
		FETCH CURSOR_NOMBRES_COMPANIAS INTO NOMBRE_COMPANIA;
		WHILE NO_MORE_DATA = 0 DO
			IF TURNO = 0 THEN 
				INSERT INTO REPORTE VALUES(TURNO, JUEGO, NOMBRE_COMPANIA, 0,0,0,0,0,0,DINERO); -- SE INSERTA UN REPORTE BASE PARA EL TURNO QUE SE ACTUALIZARA CON LOS METODOS DE CAPTURA
			ELSE
				INSERT INTO REPORTE VALUES(TURNO, JUEGO, NOMBRE_COMPANIA, 0,0,0,0,0,0,0); -- SE INSERTA UN REPORTE BASE PARA EL TURNO QUE SE ACTUALIZARA CON LOS METODOS DE CAPTURA
			END IF;
			FETCH CURSOR_NOMBRES_COMPANIAS INTO NOMBRE_COMPANIA;
		END WHILE;
		CLOSE CURSOR_NOMBRES_COMPANIAS;
		FETCH CURSOR_REPORTE_BASE INTO DINERO;	
	END WHILE;
	CLOSE CURSOR_REPORTE_BASE;
END $$