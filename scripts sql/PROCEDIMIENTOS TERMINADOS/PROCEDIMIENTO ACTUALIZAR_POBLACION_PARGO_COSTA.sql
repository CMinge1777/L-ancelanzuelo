CREATE PROCEDURE ACTUALIZAR_POBLACION_PARGO_COSTA(TURNO INT, JUEGO INT)
BEGIN 
	DECLARE NO_MORE_DATA, POBLACION_OTRA INT DEFAULT 0;
	DECLARE TASA FLOAT DEFAULT 0;
	DECLARE CURSOR_TASA_REPRODUCCION CURSOR FOR
							SELECT TASA_PARGO_C
							FROM DATOS_INICIALES;
	DECLARE CURSOR_POBLACION CURSOR FOR 
				SELECT POBLACION
				FROM   PEZ 
				WHERE  TIPO_PEZ_ID = 3 AND UBICACION_ID = 1 AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO-1;
	DECLARE  CONTINUE HANDLER FOR NOT FOUND 
		SET  NO_MORE_DATA = 1;
	OPEN CURSOR_POBLACION;
	OPEN CURSOR_TASA_REPRODUCCION;
	FETCH CURSOR_TASA_REPRODUCCION INTO TASA;
	SET TASA = TASA + 1;
	WHILE NO_MORE_DATA = 0 DO
		FETCH CURSOR_POBLACION INTO POBLACION_OTRA;
		WHILE NO_MORE_DATA = 0 DO
			INSERT INTO PEZ VALUES(3,1,POBLACION_OTRA*TASA,TURNO,JUEGO);
			FETCH CURSOR_POBLACION INTO POBLACION_OTRA;
		END WHILE;
		CLOSE CURSOR_POBLACION;
		FETCH CURSOR_TASA_REPRODUCCION INTO TASA;	
	END WHILE;
	CLOSE CURSOR_TASA_REPRODUCCION;
END $$