DROP PROCEDURE CALCULAR_CAPTURA;
CREATE PROCEDURE CALCULAR_CAPTURA(TURNO INT, JUEGO INT)
BEGIN
	DECLARE NO_MORE_DATA, CANTIDAD, UBICACION, TIPO INT DEFAULT 0;
	DECLARE NOMBRE VARCHAR(15);
	DECLARE BARCOS CURSOR FOR
						SELECT CANTIDAD_BARCOS, UBICACION_ID, TIPO_BARCO_ID, COMPANIA_NOMBRE
						FROM   BARCOSXCOMPANIA
						WHERE  JUEGO_ID = JUEGO
						ORDER BY RAND( );
	DECLARE  CONTINUE HANDLER FOR NOT FOUND 
		SET  NO_MORE_DATA = 1;
	OPEN BARCOS;
	FETCH BARCOS INTO CANTIDAD, UBICACION, TIPO, NOMBRE;
	WHILE NO_MORE_DATA = 0 DO -- SE RECORREN TODOS LOS BARCOS DE CADA COMPANIA
		CASE UBICACION -- SE DIFERENCIAN POR SU UBICACION
			WHEN 1 THEN CALL CALCULAR_CAPTURA_COSTA(CANTIDAD,TIPO,NOMBRE,TURNO,JUEGO);
			WHEN 2 THEN CALL CALCULAR_CAPTURA_MAR_PROFUNDO(CANTIDAD,TIPO,NOMBRE,TURNO,JUEGO);
			ELSE
				BEGIN
				END;
		END CASE;
		FETCH BARCOS INTO CANTIDAD, UBICACION, TIPO, NOMBRE;
	END WHILE;
	CLOSE BARCOS;
END $$

