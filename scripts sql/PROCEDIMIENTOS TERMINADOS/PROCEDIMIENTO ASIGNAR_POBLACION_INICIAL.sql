DROP PROCEDURE ASIGNAR_POBLACION_INICIAL;
CREATE PROCEDURE ASIGNAR_POBLACION_INICIAL(JUEGO_ID INT)
BEGIN
	DECLARE NO_MORE_DATA, SIERRA_C, SIERRA_M, PARGO_C, PARGO_M, ROBALO_C, ROBALO_M INT DEFAULT 0;
	DECLARE CURSOR_POBLACION CURSOR FOR 
				SELECT SIERRA_COSTA, SIERRA_MAR, PARGO_COSTA, PARGO_MAR, ROBALO_COSTA, ROBALO_MAR
				FROM DATOS_INICIALES;
	DECLARE CONTINUE HANDLER FOR NOT FOUND
		SET NO_MORE_DATA = 1;
	OPEN CURSOR_POBLACION;
	FETCH CURSOR_POBLACION INTO SIERRA_C, SIERRA_M, PARGO_C, PARGO_M, ROBALO_C, ROBALO_M;
	WHILE NO_MORE_DATA = 0 DO
		INSERT INTO PEZ VALUES(1,1,ROBALO_C,0,JUEGO_ID);
		INSERT INTO PEZ VALUES(1,2,ROBALO_M,0,JUEGO_ID);
		INSERT INTO PEZ VALUES(2,1,SIERRA_C,0,JUEGO_ID);
		INSERT INTO PEZ VALUES(2,2,SIERRA_M,0,JUEGO_ID);
		INSERT INTO PEZ VALUES(3,1,PARGO_C,0,JUEGO_ID);
		INSERT INTO PEZ VALUES(3,2,PARGO_M,0,JUEGO_ID);
		FETCH CURSOR_POBLACION INTO SIERRA_C, SIERRA_M, PARGO_C, PARGO_M, ROBALO_C, ROBALO_M;
	END WHILE;
	CLOSE CURSOR_POBLACION;	
END $$