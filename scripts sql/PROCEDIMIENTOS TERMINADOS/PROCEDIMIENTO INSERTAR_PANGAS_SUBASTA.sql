CREATE PROCEDURE INSERTAR_PANGAS_SUBASTA(NOMBRE VARCHAR(40), JUEGO INT, TURNO INT) 
BEGIN
   DECLARE NO_MORE_DATA, NUMERO_BARCOS INT DEFAULT 0;
   DECLARE CURSOR_NUMERO_PANGAS CURSOR FOR 
				SELECT NUMERO_PANGAS
				FROM SUBASTA 
				WHERE JUEGO_ID = JUEGO AND TURNO_ID = TURNO-1;
   DECLARE  CONTINUE HANDLER FOR NOT FOUND 
		SET  NO_MORE_DATA = 1;
   OPEN CURSOR_NUMERO_PANGAS;
   FETCH CURSOR_NUMERO_PANGAS INTO NUMERO_BARCOS; 
   WHILE NO_MORE_DATA = 0 DO
		CALL INSERTAR_BARCOS(NOMBRE, JUEGO,2,NUMERO_BARCOS);
		FETCH CURSOR_NUMERO_PANGAS INTO NUMERO_BARCOS; 
   END WHILE;
   CLOSE CURSOR_NUMERO_PANGAS;
END $$