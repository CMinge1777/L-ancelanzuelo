CREATE PROCEDURE INSERTAR_CHALUPAS_SUBASTA(NOMBRE VARCHAR(40), JUEGO INT, TURNO INT) -- RECORDAR QUE SUBASTA_ID ES EL TURNO EN EL QUE SE REALIZO LA SUBASTA
BEGIN
   DECLARE NO_MORE_DATA, NUMERO_BARCOS INT DEFAULT 0;
   DECLARE CURSOR_NUMERO_CHALUPAS CURSOR FOR 
				SELECT NUMERO_CHALUPAS
				FROM SUBASTA 
				WHERE JUEGO_ID = JUEGO AND TURNO_ID = TURNO-1;
   DECLARE  CONTINUE HANDLER FOR NOT FOUND 
		SET  NO_MORE_DATA = 1;
   OPEN CURSOR_NUMERO_CHALUPAS;
   FETCH CURSOR_NUMERO_CHALUPAS INTO NUMERO_BARCOS; 
   WHILE NO_MORE_DATA = 0 DO
		CALL INSERTAR_BARCOS(NOMBRE, JUEGO,1,NUMERO_BARCOS);
		FETCH CURSOR_NUMERO_CHALUPAS INTO NUMERO_BARCOS; 
   END WHILE;
   CLOSE CURSOR_NUMERO_CHALUPAS;
END $$