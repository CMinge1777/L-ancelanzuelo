								UPDATE PEZ SET POBLACION = POBLACION - CANTIDAD_PECES WHERE JUEGO_ID = JUEGO AND TURNO_ID = TURNO AND UBICACION_ID = 1 AND TIPO_PEZ_ID = 2;
								UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL+(CANTIDAD_PECES*PRECIO_SIERRA) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
							ELSEIF CANTIDAD_PECES != 0 THEN
								UPDATE REPORTE SET CAPTURA_SIERRA_COSTA = CAPTURA_SIERRA_COSTA+CANTIDAD_MAXIMA_CAPTURA WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
								UPDATE PEZ SET POBLACION = POBLACION - CANTIDAD_MAXIMA_CAPTURA WHERE JUEGO_ID = JUEGO AND TURNO_ID = TURNO AND UBICACION_ID = 1 AND TIPO_PEZ_ID = 2;
								UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL+(CANTIDAD_MAXIMA_CAPTURA*PRECIO_SIERRA) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
							END IF;
						END;
					WHEN 2 THEN
						BEGIN
							SET PROPORCION_PESCA = 0.4;
							IF CANTIDAD_ROBALO = 0 THEN
								SET PROPORCION_PESCA = PROPORCION_PESCA + 0.14;
							END IF;
							IF CANTIDAD_PARGO = 0 THEN
								SET PROPORCION_PESCA = PROPORCION_PESCA + 0.16;
							END IF;
							SET CANTIDAD_MAXIMA_CAPTURA = CAPACIDAD_PANGA*CANTIDAD_BARCOS*PROPORCION_PESCA;
							IF CANTIDAD_PECES < CANTIDAD_MAXIMA_CAPTURA THEN
								UPDATE REPORTE SET CAPTURA_SIERRA_COSTA = CAPTURA_SIERRA_COSTA+CANTIDAD_PECES WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
								UPDATE PEZ SET POBLACION = POBLACION - CANTIDAD_PECES WHERE JUEGO_ID = JUEGO AND TURNO_ID = TURNO AND UBICACION_ID = 1 AND TIPO_PEZ_ID = 2;
								UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL+(CANTIDAD_PECES*PRECIO_SIERRA) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
							ELSEIF CANTIDAD_PECES != 0 THEN
								UPDATE REPORTE SET CAPTURA_SIERRA_COSTA = CAPTURA_SIERRA_COSTA+CANTIDAD_MAXIMA_CAPTURA WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
								UPDATE PEZ SET POBLACION = POBLACION - CANTIDAD_MAXIMA_CAPTURA WHERE JUEGO_ID = JUEGO AND TURNO_ID = TURNO AND UBICACION_ID = 1 AND TIPO_PEZ_ID = 2;
								UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL+(CANTIDAD_MAXIMA_CAPTURA*PRECIO_SIERRA) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
							END IF;
						END;
					WHEN 3 THEN
						BEGIN
							SET PROPORCION_PESCA = 0.35;
							IF CANTIDAD_ROBALO = 0 THEN
								SET PROPORCION_PESCA = PROPORCION_PESCA + 0.2;
							END IF;
							IF CANTIDAD_PARGO = 0 THEN
								SET PROPORCION_PESCA = PROPORCION_PESCA + 0.125;
							END IF;
							SET CANTIDAD_MAXIMA_CAPTURA = CAPACIDAD_BARCO*CANTIDAD_BARCOS*PROPORCION_PESCA;
							IF CANTIDAD_PECES < CANTIDAD_MAXIMA_CAPTURA THEN
								UPDATE REPORTE SET CAPTURA_SIERRA_COSTA = CAPTURA_SIERRA_COSTA+CANTIDAD_PECES WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
								UPDATE PEZ SET POBLACION = POBLACION - CANTIDAD_PECES WHERE JUEGO_ID = JUEGO AND TURNO_ID = TURNO AND UBICACION_ID = 1 AND TIPO_PEZ_ID = 2;
								UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL+(CANTIDAD_PECES*PRECIO_SIERRA) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
							ELSEIF CANTIDAD_PECES != 0 THEN
								UPDATE REPORTE SET CAPTURA_SIERRA_COSTA = CAPTURA_SIERRA_COSTA+CANTIDAD_MAXIMA_CAPTURA WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
								UPDATE PEZ SET POBLACION = POBLACION - CANTIDAD_MAXIMA_CAPTURA WHERE JUEGO_ID = JUEGO AND TURNO_ID = TURNO AND UBICACION_ID = 1 AND TIPO_PEZ_ID = 2;
								UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL+(CANTIDAD_MAXIMA_CAPTURA*PRECIO_SIERRA) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
							END IF;
						END;
					END CASE;
			WHEN 3 THEN
				CASE TIPO
					WHEN 1 THEN
						BEGIN
							SET PROPORCION_PESCA = 0.18;
							IF CANTIDAD_ROBALO = 0 THEN
								SET PROPORCION_PESCA = PROPORCION_PESCA + 0.275;
							END IF;
							IF CANTIDAD_SIERRA = 0 THEN
								SET PROPORCION_PESCA = PROPORCION_PESCA + 0.175;
