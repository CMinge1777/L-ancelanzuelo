DROP PROCEDURE CALCULAR_CAPTURA_COSTA;
CREATE PROCEDURE CALCULAR_CAPTURA_COSTA(CANTIDAD_BARCOS INT,TIPO INT,NOMBRE VARCHAR(15), TURNO INT, JUEGO INT)
BEGIN
	DECLARE VALOR, TIPO_PEZ_PRECIO, NO_MORE_DATA, TIPO_PEZ, CANTIDAD_MAXIMA_CAPTURA, PRECIO_ROBALO, PRECIO_SIERRA, PRECIO_PARGO INT DEFAULT 0;
	DECLARE BARCO_ID, CAPACIDAD_PESCA, CAPACIDAD_CHALUPA, CAPACIDAD_BARCO, CAPACIDAD_PANGA,CANTIDAD_PECES, CANTIDAD_ROBALO, CANTIDAD_SIERRA, CANTIDAD_PARGO INT DEFAULT 0;
	DECLARE PROPORCION_PESCA FLOAT DEFAULT 0;
	DECLARE POBLACION CURSOR FOR
						SELECT TIPO_PEZ_ID, POBLACION
						FROM   PEZ
						WHERE  JUEGO_ID = JUEGO AND TURNO_ID = TURNO AND UBICACION_ID = 1;
	DECLARE VERIFICADOR_POBLACION CURSOR FOR
						SELECT TIPO_PEZ_ID, POBLACION
						FROM   PEZ
						WHERE  JUEGO_ID = JUEGO AND TURNO_ID = TURNO AND UBICACION_ID = 1;
	DECLARE CURSOR_PRECIO_PECES CURSOR FOR
						SELECT TIPO_PEZ_ID, PRECIO
						FROM   TIPO_PEZ;
	DECLARE CURSOR_CAPACIDADES CURSOR FOR
						SELECT TIPO_BARCO_ID, CAPACIDAD
						FROM   TIPO_BARCO;
	DECLARE CONTINUE HANDLER FOR NOT FOUND
		SET NO_MORE_DATA = 1;
		
	OPEN VERIFICADOR_POBLACION;
	FETCH VERIFICADOR_POBLACION INTO TIPO_PEZ,CANTIDAD_PECES;
	WHILE NO_MORE_DATA = 0 DO
		CASE TIPO_PEZ 	
			WHEN 1 THEN SET CANTIDAD_ROBALO = CANTIDAD_PECES;
			WHEN 2 THEN SET CANTIDAD_SIERRA = CANTIDAD_PECES;
			WHEN 3 THEN SET CANTIDAD_PARGO  = CANTIDAD_PECES;
		END CASE;
		FETCH VERIFICADOR_POBLACION INTO TIPO_PEZ,CANTIDAD_PECES;
	END WHILE;
	CLOSE VERIFICADOR_POBLACION;
	SET NO_MORE_DATA = 0;
	SET CANTIDAD_PECES = 0;

	OPEN CURSOR_CAPACIDADES;
	FETCH CURSOR_CAPACIDADES INTO BARCO_ID, CAPACIDAD_PESCA;
	WHILE NO_MORE_DATA = 0 DO
		CASE BARCO_ID 	
			WHEN 1 THEN SET CAPACIDAD_CHALUPA = CAPACIDAD_PESCA;
			WHEN 2 THEN SET CAPACIDAD_PANGA   = CAPACIDAD_PESCA;
			WHEN 3 THEN SET CAPACIDAD_BARCO   = CAPACIDAD_PESCA;
		END CASE;
		FETCH CURSOR_CAPACIDADES INTO BARCO_ID, CAPACIDAD_PESCA;
	END WHILE;
	CLOSE CURSOR_CAPACIDADES;
	SET NO_MORE_DATA = 0;
	
	OPEN CURSOR_PRECIO_PECES;
	FETCH CURSOR_PRECIO_PECES INTO TIPO_PEZ_PRECIO, VALOR;
	WHILE NO_MORE_DATA = 0 DO -- SE ALMACENAN LOS PRECIOS DE CADA TIPO DE PEZ
		CASE TIPO_PEZ_PRECIO
			WHEN 1 THEN SET PRECIO_ROBALO = VALOR;
			WHEN 2 THEN SET PRECIO_SIERRA = VALOR;
			WHEN 3 THEN SET PRECIO_PARGO  = VALOR;
		END CASE;
		FETCH CURSOR_PRECIO_PECES INTO TIPO_PEZ_PRECIO, VALOR;
	END WHILE;
	CLOSE CURSOR_PRECIO_PECES;
	SET NO_MORE_DATA = 0;
	
	OPEN POBLACION;
	FETCH POBLACION INTO TIPO_PEZ,CANTIDAD_PECES;
	WHILE NO_MORE_DATA = 0 DO -- SE RECORREN TODOS LOS TIPOS DE PECES QUE HAY EN MAR PROFUNDO
		CASE TIPO_PEZ -- SE SEGMENTAN DEPENDIENDO DEL TIPO DE PEZ
			WHEN 1 THEN
				CASE TIPO -- SE SEGMENTA DEPENDIENDO EL TIPO DE EMBARCACION
					WHEN 1 THEN
						BEGIN
							SET PROPORCION_PESCA = 0.55;
							IF CANTIDAD_SIERRA = 0 THEN
								SET PROPORCION_PESCA = PROPORCION_PESCA + 0.135;
							END IF;
							IF CANTIDAD_PARGO = 0 THEN	
								SET PROPORCION_PESCA = PROPORCION_PESCA + 0.09;
							END IF;
							SET CANTIDAD_MAXIMA_CAPTURA = CAPACIDAD_CHALUPA*CANTIDAD_BARCOS*PROPORCION_PESCA;
							IF CANTIDAD_PECES < CANTIDAD_MAXIMA_CAPTURA THEN -- SE VERIFICA SI LA CAPACIDAD DE PESCA EXCEDE LA CANTIDAD DE PECES DE LA ZONA, EN CASO AFIRMATIVO SE CAPTURAN TODOS LOS PECES DISPONIBLES
								UPDATE REPORTE SET CAPTURA_ROBALO_COSTA = CAPTURA_ROBALO_COSTA+CANTIDAD_PECES WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
								UPDATE PEZ SET POBLACION = POBLACION - CANTIDAD_PECES WHERE JUEGO_ID = JUEGO AND TURNO_ID = TURNO AND UBICACION_ID = 1 AND TIPO_PEZ_ID = 1;
								UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL+(CANTIDAD_PECES*PRECIO_ROBALO) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
							ELSEIF CANTIDAD_PECES != 0 THEN -- EN CASO DE HABER MAS PECES QUE LA CAPACIDAD DE PESCA, SE CAPTURA LA CAPACIDAD MAXIMA
								UPDATE REPORTE SET CAPTURA_ROBALO_COSTA = CAPTURA_ROBALO_COSTA+CANTIDAD_MAXIMA_CAPTURA WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
								UPDATE PEZ SET POBLACION = POBLACION - CANTIDAD_MAXIMA_CAPTURA WHERE JUEGO_ID = JUEGO AND TURNO_ID = TURNO AND UBICACION_ID = 1 AND TIPO_PEZ_ID = 1;
								UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL+(CANTIDAD_MAXIMA_CAPTURA*PRECIO_ROBALO) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
							END IF;
						END;
					WHEN 2 THEN
						BEGIN
							SET PROPORCION_PESCA = 0.28;
							IF CANTIDAD_SIERRA = 0 THEN
								SET PROPORCION_PESCA = PROPORCION_PESCA + 0.2;
							END IF;
							IF CANTIDAD_PARGO = 0 THEN
