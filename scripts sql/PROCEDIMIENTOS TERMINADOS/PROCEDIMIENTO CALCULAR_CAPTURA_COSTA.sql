								UPDATE PEZ SET POBLACION = POBLACION - CANTIDAD_PECES WHERE JUEGO_ID = JUEGO AND TURNO_ID = TURNO AND UBICACION_ID = 1 AND TIPO_PEZ_ID = 3;
