								UPDATE PEZ SET POBLACION = POBLACION - CANTIDAD_PECES WHERE JUEGO_ID = JUEGO AND TURNO_ID = TURNO AND UBICACION_ID = 1 AND TIPO_PEZ_ID = 1;
								UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL+(CANTIDAD_PECES*PRECIO_ROBALO) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
							ELSEIF CANTIDAD_PECES != 0 THEN
								UPDATE REPORTE SET CAPTURA_ROBALO_COSTA = CAPTURA_ROBALO_COSTA+CANTIDAD_MAXIMA_CAPTURA WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
								UPDATE PEZ SET POBLACION = POBLACION - CANTIDAD_MAXIMA_CAPTURA WHERE JUEGO_ID = JUEGO AND TURNO_ID = TURNO AND UBICACION_ID = 1 AND TIPO_PEZ_ID = 1;
								UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL+(CANTIDAD_MAXIMA_CAPTURA*PRECIO_ROBALO) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
							END IF;
						END;
					WHEN 3 THEN
