							IF CANTIDAD_SIERRA = 0 THEN
								SET PROPORCION_PESCA = PROPORCION_PESCA + 0.175;
							END IF;
							IF CANTIDAD_PARGO = 0 THEN
								SET PROPORCION_PESCA = PROPORCION_PESCA + 0.125;
