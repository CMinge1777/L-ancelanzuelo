CREATE PROCEDURE INSERTAR_PESQUEROS_SUBASTA(NOMBRE VARCHAR(40), JUEGO INT, TURNO INT)
BEGIN
   DECLARE NO_MORE_DATA, NUMERO_BARCOS INT DEFAULT 0;
   DECLARE CURSOR_NUMERO_PESQUEROS CURSOR FOR 
				SELECT NUMERO_BARCO_PESQUERO
				FROM SUBASTA 
				WHERE JUEGO_ID = JUEGO AND TURNO_ID = TURNO-1;
   DECLARE  CONTINUE HANDLER FOR NOT FOUND 
		SET  NO_MORE_DATA = 1;
   OPEN CURSOR_NUMERO_PESQUEROS;
   FETCH CURSOR_NUMERO_PESQUEROS INTO NUMERO_BARCOS; 
   WHILE NO_MORE_DATA = 0 DO
		CALL INSERTAR_BARCOS(NOMBRE, JUEGO,3,NUMERO_BARCOS);
		FETCH CURSOR_NUMERO_PESQUEROS INTO NUMERO_BARCOS; 
   END WHILE;
   CLOSE CURSOR_NUMERO_PESQUEROS;
END $$