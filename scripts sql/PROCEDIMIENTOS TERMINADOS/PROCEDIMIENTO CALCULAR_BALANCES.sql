CREATE PROCEDURE CALCULAR_BALANCES(JUEGO INT)
BEGIN
	DECLARE NO_MORE_DATA INT DEFAULT 0;
	DECLARE NOMBRE_COMPANIA VARCHAR(15);
	DECLARE CURSOR_COMPANIAS CURSOR FOR
							 SELECT NOMBRE 
							 FROM COMPANIA
							 WHERE JUEGO_ID = JUEGO;
	DECLARE CONTINUE HANDLER FOR NOT FOUND
		SET NO_MORE_DATA = 1;
	OPEN CURSOR_COMPANIAS;
	FETCH CURSOR_COMPANIAS INTO NOMBRE_COMPANIA;
	WHILE NO_MORE_DATA = 0 DO
		CALL CALCULAR_BALANCE(JUEGO, NOMBRE_COMPANIA);
		FETCH CURSOR_COMPANIAS INTO NOMBRE_COMPANIA;
	END WHILE;
	CLOSE CURSOR_COMPANIAS;
END $$