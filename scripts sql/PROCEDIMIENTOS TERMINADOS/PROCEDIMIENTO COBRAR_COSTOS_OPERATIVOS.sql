DROP PROCEDURE COBRAR_COSTOS_OPERATIVOS;
CREATE PROCEDURE COBRAR_COSTOS_OPERATIVOS(TURNO INT, JUEGO INT)
BEGIN
	DECLARE DUMMY_ID, COSTO_UBICACION, COSTO_TIPO_BARCO, COSTO_VALOR, NO_MORE_DATA INT DEFAULT 0;
	DECLARE COSTO_COSTA_CHALUPA, COSTO_COSTA_BARCO, COSTO_COSTA_PANGA, COSTO_PUERTO_BARCO, COSTO_PUERTO_PANGA, COSTO_PUERTO_CHALUPA, COSTO_MAR_PANGA, COSTO_MAR_BARCO, COSTO_MAR_CHALUPA INT DEFAULT 0;
	DECLARE CANTIDAD, UBICACION, TIPO INT DEFAULT 0;
	DECLARE NOMBRE VARCHAR(15);
	DECLARE CURSOR_COSTOS_OPERATIVOS CURSOR FOR
										SELECT * 
										FROM COSTOSXUBICACIONXTIPO;
	DECLARE BARCOS CURSOR FOR
						SELECT CANTIDAD_BARCOS, UBICACION_ID, TIPO_BARCO_ID, COMPANIA_NOMBRE
						FROM   BARCOSXCOMPANIA
						WHERE  JUEGO_ID = JUEGO;
	DECLARE CONTINUE HANDLER FOR NOT FOUND
		SET NO_MORE_DATA = 1;
	OPEN CURSOR_COSTOS_OPERATIVOS;
	FETCH CURSOR_COSTOS_OPERATIVOS INTO DUMMY_ID, COSTO_UBICACION, COSTO_TIPO_BARCO, COSTO_VALOR;
	WHILE NO_MORE_DATA = 0 DO
		CASE COSTO_UBICACION
			WHEN 0 THEN
				CASE COSTO_TIPO_BARCO
					WHEN 1 THEN SET COSTO_PUERTO_CHALUPA = COSTO_VALOR;
					WHEN 2 THEN SET COSTO_PUERTO_PANGA   = COSTO_VALOR;
					WHEN 3 THEN SET COSTO_PUERTO_BARCO   = COSTO_VALOR;
				END CASE;
			WHEN 1 THEN
				CASE COSTO_TIPO_BARCO
					WHEN 1 THEN SET COSTO_COSTA_CHALUPA = COSTO_VALOR;
					WHEN 2 THEN SET COSTO_COSTA_PANGA   = COSTO_VALOR;
					WHEN 3 THEN SET COSTO_COSTA_BARCO   = COSTO_VALOR;
				END CASE;
			WHEN 2 THEN
				CASE COSTO_TIPO_BARCO
					WHEN 1 THEN SET COSTO_MAR_CHALUPA = COSTO_VALOR;
					WHEN 2 THEN SET COSTO_MAR_PANGA   = COSTO_VALOR;
					WHEN 3 THEN SET COSTO_MAR_BARCO   = COSTO_VALOR;
				END CASE;
		END CASE;
		FETCH CURSOR_COSTOS_OPERATIVOS INTO DUMMY_ID, COSTO_UBICACION, COSTO_TIPO_BARCO, COSTO_VALOR;
	END WHILE;
	CLOSE CURSOR_COSTOS_OPERATIVOS;
	SET NO_MORE_DATA = 0;
	OPEN BARCOS;
	FETCH BARCOS INTO CANTIDAD, UBICACION, TIPO, NOMBRE;
	WHILE NO_MORE_DATA = 0 DO -- SE RECORREN TODOS LOS BARCOS DE CADA COMPANIA
		CASE UBICACION
			WHEN 0 THEN
				CASE TIPO
					WHEN 1 THEN UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL-(CANTIDAD*COSTO_PUERTO_CHALUPA) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
					WHEN 2 THEN UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL-(CANTIDAD*COSTO_PUERTO_PANGA) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
					WHEN 3 THEN UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL-(CANTIDAD*COSTO_PUERTO_BARCO) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
				END CASE;
			WHEN 1 THEN
				CASE TIPO
					WHEN 1 THEN UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL-(CANTIDAD*COSTO_COSTA_CHALUPA) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
					WHEN 2 THEN UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL-(CANTIDAD*COSTO_COSTA_PANGA) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
					WHEN 3 THEN UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL-(CANTIDAD*COSTO_COSTA_BARCO) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
				END CASE;
			WHEN 2 THEN
				CASE TIPO
					WHEN 1 THEN UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL-(CANTIDAD*COSTO_MAR_CHALUPA) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
					WHEN 2 THEN UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL-(CANTIDAD*COSTO_MAR_PANGA) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
					WHEN 3 THEN UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL-(CANTIDAD*COSTO_MAR_BARCO) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
				END CASE;
		END CASE;
		FETCH BARCOS INTO CANTIDAD, UBICACION, TIPO, NOMBRE;
	END WHILE;
	CLOSE BARCOS;
END $$