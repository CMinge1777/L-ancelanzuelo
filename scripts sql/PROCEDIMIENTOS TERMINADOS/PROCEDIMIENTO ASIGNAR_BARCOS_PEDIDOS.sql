DROP PROCEDURE IF EXISTS ASIGNAR_BARCOS_PEDIDOS;
CREATE PROCEDURE ASIGNAR_BARCOS_PEDIDOS(TURNO INT, JUEGO INT)
BEGIN
	DECLARE NOMBRE_COMPANIA VARCHAR(15);
	DECLARE TIPO_BARCO, VALOR, CANTIDAD_CHALUPAS, CANTIDAD_PANGAS, CANTIDAD_BARCOS_PESQUEROS, NO_MORE_DATA, VALOR_INSERTAR, PRECIO_CHALUPA, PRECIO_BARCO, PRECIO_PANGA INT DEFAULT 0;
	DECLARE CURSOR_PEDIDOS CURSOR FOR 
								SELECT COMPANIA_NOMBRE, NUMERO_CHALUPAS, NUMERO_PANGAS, NUMERO_BARCO_PESQUERO
								FROM   PEDIDO 
								WHERE  JUEGO_ID = JUEGO AND TURNO_ID = TURNO-1;
	DECLARE CURSOR_PRECIOS CURSOR FOR
								SELECT TIPO_BARCO_ID, PRECIO
								FROM TIPO_BARCO;
	DECLARE  CONTINUE HANDLER FOR NOT FOUND 
		SET  NO_MORE_DATA = 1;
	OPEN CURSOR_PRECIOS;
	FETCH CURSOR_PRECIOS INTO TIPO_BARCO, VALOR;
	WHILE NO_MORE_DATA = 0 DO
		CASE TIPO_BARCO 
			WHEN 1 THEN SET PRECIO_CHALUPA = VALOR;
			WHEN 2 THEN SET PRECIO_PANGA   = VALOR;
			WHEN 3 THEN SET PRECIO_BARCO   = VALOR;
		END CASE;
		FETCH CURSOR_PRECIOS INTO TIPO_BARCO, VALOR;
	END WHILE;
	CLOSE CURSOR_PRECIOS;
	SET NO_MORE_DATA = 0;
	OPEN CURSOR_PEDIDOS;
	FETCH CURSOR_PEDIDOS INTO NOMBRE_COMPANIA, CANTIDAD_CHALUPAS,CANTIDAD_PANGAS,CANTIDAD_BARCOS_PESQUEROS;
	WHILE NO_MORE_DATA = 0 DO
		CALL INSERTAR_BARCOS(NOMBRE_COMPANIA, JUEGO, 1 ,CANTIDAD_CHALUPAS);
		UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL - CANTIDAD_CHALUPAS*PRECIO_CHALUPA WHERE JUEGO_ID = JUEGO AND COMPANIA_NOMBRE = NOMBRE_COMPANIA AND TURNO_ID = TURNO;
		CALL INSERTAR_BARCOS(NOMBRE_COMPANIA, JUEGO, 2 ,CANTIDAD_PANGAS);
		UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL - CANTIDAD_PANGAS*PRECIO_PANGA WHERE JUEGO_ID = JUEGO AND COMPANIA_NOMBRE = NOMBRE_COMPANIA AND TURNO_ID = TURNO;
		CALL INSERTAR_BARCOS(NOMBRE_COMPANIA, JUEGO, 3 ,CANTIDAD_BARCOS_PESQUEROS);
		UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL - CANTIDAD_BARCOS_PESQUEROS*PRECIO_BARCO WHERE JUEGO_ID = JUEGO AND COMPANIA_NOMBRE = NOMBRE_COMPANIA AND TURNO_ID = TURNO;
		FETCH CURSOR_PEDIDOS INTO NOMBRE_COMPANIA, CANTIDAD_CHALUPAS,CANTIDAD_PANGAS,CANTIDAD_BARCOS_PESQUEROS;
	END WHILE;
	CLOSE CURSOR_PEDIDOS;
END $$