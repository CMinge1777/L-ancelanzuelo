CREATE PROCEDURE TURNO_FINALIZADO(TURNO_ID INT, JUEGO_ID INT)
BEGIN
	IF TURNO_ID = 0 THEN
		CALL ASIGNAR_POBLACION_INICIAL(JUEGO_ID);		   -- LISTO
		CALL INSERTAR_BARCOS_INICIALES(JUEGO_ID);		   -- LISTO
		CALL INSERTAR_REPORTE_BASE(TURNO_ID, JUEGO_ID);	   -- LISTO
	ELSEIF TURNO_ID = 12 THEN 
		UPDATE JUEGO SET FINALIZADO = 1 WHERE JUEGO_ID = JUEGO_ID;
	ELSE
		CALL INSERTAR_REPORTE_BASE(TURNO_ID, JUEGO_ID);    -- LISTO
		CALL POSICIONAR_EMBARCACIONES(TURNO_ID, JUEGO_ID); -- LISTO
		CALL COBRAR_COSTOS_OPERATIVOS(TURNO_ID, JUEGO_ID); -- LISTO
		CALL REPRODUCIR_PECES(TURNO_ID, JUEGO_ID);		   -- LISTO
		CALL ASIGNAR_BARCOS_SUBASTA(TURNO_ID, JUEGO_ID);   -- LISTO
		CALL CALCULAR_CAPTURA(TURNO_ID, JUEGO_ID);         -- LISTO
		CALL ASIGNAR_BARCOS_PEDIDOS(TURNO_ID, JUEGO_ID);   -- LISTO
		CALL CALCULAR_BALANCES(JUEGO_ID);
	END IF;
END $$
