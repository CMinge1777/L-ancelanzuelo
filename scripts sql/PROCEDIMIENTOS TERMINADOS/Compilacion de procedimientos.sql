								UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL+(CANTIDAD_PECES*PRECIO_PARGO) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
