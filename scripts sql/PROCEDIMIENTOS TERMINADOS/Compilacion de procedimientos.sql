CREATE FUNCTION GET_TURNO(JUEGO INT) RETURNS INT
BEGIN
	DECLARE TURNO INT DEFAULT 0;
	SELECT    MAX(TURNO_ID) INTO TURNO
	FROM      TURNO
	WHERE     JUEGO_ID = JUEGO
	ORDER BY  TURNO_ID DESC 
	LIMIT 1;
    RETURN(TURNO);
END$$
