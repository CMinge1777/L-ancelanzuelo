							END IF;
						END;
					WHEN 3 THEN
						BEGIN
							SET CANTIDAD_MAXIMA_CAPTURA = CAPACIDAD_BARCO*CANTIDAD_BARCOS*0.40;
							IF CANTIDAD_PECES < CANTIDAD_MAXIMA_CAPTURA THEN
