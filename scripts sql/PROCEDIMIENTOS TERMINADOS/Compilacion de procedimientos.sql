CREATE PROCEDURE POSICIONAR_EMBARCACIONES(TURNO INT, JUEGO INT)
BEGIN
	DECLARE NO_MORE_DATA, CHALUPAS_COSTA, CHALUPAS_MAR, CHALUPAS_PUERTO, PANGA_COSTA, PANGA_MAR	INT DEFAULT 0;
	DECLARE PANGA_PUERTO, BARCO_COSTA, BARCO_PUERTO, BARCO_MAR INT DEFAULT 0;
	DECLARE NOMBRE VARCHAR(15);
	DECLARE CURSOR_DECISION CURSOR FOR
							SELECT *
							FROM   DECISION
							WHERE  JUEGO_ID = JUEGO AND TURNO_ID = TURNO-1;
	DECLARE CONTINUE HANDLER FOR NOT FOUND
		SET NO_MORE_DATA = 1;
	OPEN CURSOR_DECISION;
	FETCH CURSOR_DECISION INTO NOMBRE, JUEGO, TURNO, CHALUPAS_COSTA, CHALUPAS_MAR, CHALUPAS_PUERTO, PANGA_COSTA, PANGA_MAR, PANGA_PUERTO, BARCO_COSTA, BARCO_PUERTO, BARCO_MAR;
	WHILE NO_MORE_DATA = 0 DO
		UPDATE BARCOSXCOMPANIA SET CANTIDAD_BARCOS = CHALUPAS_PUERTO WHERE UBICACION_ID = 0 AND TIPO_BARCO_ID = 1 AND JUEGO_ID = JUEGO AND COMPANIA_NOMBRE = NOMBRE;
		UPDATE BARCOSXCOMPANIA SET CANTIDAD_BARCOS = CHALUPAS_COSTA  WHERE UBICACION_ID = 1 AND TIPO_BARCO_ID = 1 AND JUEGO_ID = JUEGO AND COMPANIA_NOMBRE = NOMBRE;
		UPDATE BARCOSXCOMPANIA SET CANTIDAD_BARCOS = CHALUPAS_MAR    WHERE UBICACION_ID = 2 AND TIPO_BARCO_ID = 1 AND JUEGO_ID = JUEGO AND COMPANIA_NOMBRE = NOMBRE;
		UPDATE BARCOSXCOMPANIA SET CANTIDAD_BARCOS = PANGA_PUERTO    WHERE UBICACION_ID = 0 AND TIPO_BARCO_ID = 2 AND JUEGO_ID = JUEGO AND COMPANIA_NOMBRE = NOMBRE;
		UPDATE BARCOSXCOMPANIA SET CANTIDAD_BARCOS = PANGA_COSTA     WHERE UBICACION_ID = 1 AND TIPO_BARCO_ID = 2 AND JUEGO_ID = JUEGO AND COMPANIA_NOMBRE = NOMBRE;
		UPDATE BARCOSXCOMPANIA SET CANTIDAD_BARCOS = PANGA_MAR       WHERE UBICACION_ID = 2 AND TIPO_BARCO_ID = 2 AND JUEGO_ID = JUEGO AND COMPANIA_NOMBRE = NOMBRE;
		UPDATE BARCOSXCOMPANIA SET CANTIDAD_BARCOS = BARCO_PUERTO    WHERE UBICACION_ID = 0 AND TIPO_BARCO_ID = 3 AND JUEGO_ID = JUEGO AND COMPANIA_NOMBRE = NOMBRE;
		UPDATE BARCOSXCOMPANIA SET CANTIDAD_BARCOS = BARCO_COSTA     WHERE UBICACION_ID = 1 AND TIPO_BARCO_ID = 3 AND JUEGO_ID = JUEGO AND COMPANIA_NOMBRE = NOMBRE;
		UPDATE BARCOSXCOMPANIA SET CANTIDAD_BARCOS = BARCO_MAR       WHERE UBICACION_ID = 2 AND TIPO_BARCO_ID = 3 AND JUEGO_ID = JUEGO AND COMPANIA_NOMBRE = NOMBRE;
		FETCH CURSOR_DECISION INTO NOMBRE, JUEGO, TURNO, CHALUPAS_COSTA, CHALUPAS_MAR, CHALUPAS_PUERTO, PANGA_COSTA, PANGA_MAR, PANGA_PUERTO, BARCO_COSTA, BARCO_PUERTO, BARCO_MAR;
	END WHILE;
	CLOSE CURSOR_DECISION;
END $$
