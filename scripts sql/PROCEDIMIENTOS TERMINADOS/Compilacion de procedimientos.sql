								UPDATE REPORTE SET CAPTURA_PARGO_MAR_PROFUNDO = CAPTURA_PARGO_MAR_PROFUNDO+CANTIDAD_MAXIMA_CAPTURA WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
								UPDATE PEZ SET POBLACION = POBLACION - CANTIDAD_MAXIMA_CAPTURA WHERE JUEGO_ID = JUEGO AND TURNO_ID = TURNO AND UBICACION_ID = 2 AND TIPO_PEZ_ID = 3;
								UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL+(CANTIDAD_MAXIMA_CAPTURA*PRECIO_PARGO) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
							END IF;
						END;
					ELSE
						BEGIN
						END;
				END CASE;
			ELSE
				BEGIN
				END;
		END CASE;
		FETCH POBLACION INTO TIPO_PEZ,CANTIDAD_PECES;
	END WHILE;
	CLOSE POBLACION;
END $$
CREATE PROCEDURE COBRAR_COSTOS_OPERATIVOS(TURNO INT, JUEGO INT)
BEGIN
	DECLARE DUMMY_ID, COSTO_UBICACION, COSTO_TIPO_BARCO, COSTO_VALOR, NO_MORE_DATA INT DEFAULT 0;
	DECLARE COSTO_COSTA_CHALUPA, COSTO_COSTA_BARCO, COSTO_COSTA_PANGA, COSTO_PUERTO_BARCO, COSTO_PUERTO_PANGA, COSTO_PUERTO_CHALUPA, COSTO_MAR_PANGA, COSTO_MAR_BARCO, COSTO_MAR_CHALUPA INT DEFAULT 0;
	DECLARE CANTIDAD, UBICACION, TIPO INT DEFAULT 0;
	DECLARE NOMBRE VARCHAR(15);
	DECLARE CURSOR_COSTOS_OPERATIVOS CURSOR FOR
										SELECT * 
										FROM COSTOSXUBICACIONXTIPO;
	DECLARE BARCOS CURSOR FOR
						SELECT CANTIDAD_BARCOS, UBICACION_ID, TIPO_BARCO_ID, COMPANIA_NOMBRE
						FROM   BARCOSXCOMPANIA
						WHERE  JUEGO_ID = JUEGO;
	DECLARE CONTINUE HANDLER FOR NOT FOUND
		SET NO_MORE_DATA = 1;
	OPEN CURSOR_COSTOS_OPERATIVOS;
	FETCH CURSOR_COSTOS_OPERATIVOS INTO DUMMY_ID, COSTO_UBICACION, COSTO_TIPO_BARCO, COSTO_VALOR;
	WHILE NO_MORE_DATA = 0 DO
		CASE COSTO_UBICACION
			WHEN 0 THEN
				CASE COSTO_TIPO_BARCO
					WHEN 1 THEN SET COSTO_PUERTO_CHALUPA = COSTO_VALOR;
					WHEN 2 THEN SET COSTO_PUERTO_PANGA   = COSTO_VALOR;
					WHEN 3 THEN SET COSTO_PUERTO_BARCO   = COSTO_VALOR;
				END CASE;
			WHEN 1 THEN
				CASE COSTO_TIPO_BARCO
					WHEN 1 THEN SET COSTO_COSTA_CHALUPA = COSTO_VALOR;
					WHEN 2 THEN SET COSTO_COSTA_PANGA   = COSTO_VALOR;
					WHEN 3 THEN SET COSTO_COSTA_BARCO   = COSTO_VALOR;
				END CASE;
			WHEN 2 THEN
				CASE COSTO_TIPO_BARCO
					WHEN 1 THEN SET COSTO_MAR_CHALUPA = COSTO_VALOR;
					WHEN 2 THEN SET COSTO_MAR_PANGA   = COSTO_VALOR;
					WHEN 3 THEN SET COSTO_MAR_BARCO   = COSTO_VALOR;
				END CASE;
		END CASE;
		FETCH CURSOR_COSTOS_OPERATIVOS INTO DUMMY_ID, COSTO_UBICACION, COSTO_TIPO_BARCO, COSTO_VALOR;
	END WHILE;
	CLOSE CURSOR_COSTOS_OPERATIVOS;
	SET NO_MORE_DATA = 0;
	OPEN BARCOS;
	FETCH BARCOS INTO CANTIDAD, UBICACION, TIPO, NOMBRE;
	WHILE NO_MORE_DATA = 0 DO -- SE RECORREN TODOS LOS BARCOS DE CADA COMPANIA
		CASE UBICACION
			WHEN 0 THEN
				CASE TIPO
					WHEN 1 THEN UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL-(CANTIDAD*COSTO_PUERTO_CHALUPA) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
					WHEN 2 THEN UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL-(CANTIDAD*COSTO_PUERTO_PANGA) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
					WHEN 3 THEN UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL-(CANTIDAD*COSTO_PUERTO_BARCO) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
				END CASE;
			WHEN 1 THEN
				CASE TIPO
					WHEN 1 THEN UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL-(CANTIDAD*COSTO_COSTA_CHALUPA) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
					WHEN 2 THEN UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL-(CANTIDAD*COSTO_COSTA_PANGA) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
					WHEN 3 THEN UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL-(CANTIDAD*COSTO_COSTA_BARCO) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
				END CASE;
			WHEN 2 THEN
				CASE TIPO
					WHEN 1 THEN UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL-(CANTIDAD*COSTO_MAR_CHALUPA) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
					WHEN 2 THEN UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL-(CANTIDAD*COSTO_MAR_PANGA) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
					WHEN 3 THEN UPDATE REPORTE SET BALANCE_GENERAL = BALANCE_GENERAL-(CANTIDAD*COSTO_MAR_BARCO) WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
				END CASE;
		END CASE;
		FETCH BARCOS INTO CANTIDAD, UBICACION, TIPO, NOMBRE;
	END WHILE;
	CLOSE BARCOS;
END $$
CREATE PROCEDURE INSERTAR_BARCOS(NOMBRE VARCHAR(40), JUEGO INT, TIPO INT,CANTIDAD INT)
BEGIN
	DECLARE NUMERO_BARCOS,NO_MORE_DATA INT DEFAULT 0;
	DECLARE CURSOR_CANTIDAD_BARCOS CURSOR FOR 
									SELECT CANTIDAD_BARCOS
									FROM BARCOSXCOMPANIA
									WHERE JUEGO_ID = JUEGO AND COMPANIA_NOMBRE = NOMBRE AND UBICACION_ID = 0 AND TIPO_BARCO_ID = TIPO;
	DECLARE  CONTINUE HANDLER FOR NOT FOUND 
		SET  NO_MORE_DATA = 1;
	OPEN CURSOR_CANTIDAD_BARCOS;
	FETCH CURSOR_CANTIDAD_BARCOS INTO NUMERO_BARCOS;
	IF NO_MORE_DATA = 1 THEN -- SI NO EXISTEN BARCOS EN EL PUERTO ENTONCES SE REALIZA UNA INSERCION CON LA NUEVA CANTIDAD DE BARCOS QUE SE VAN A INSERTAR
		IF CANTIDAD > 0 THEN -- SE SE ENVIA NUMERO DE BARCOS IGUAL A CERO ENTONCES NO SE INSERTA NADA
			INSERT INTO BARCOSXCOMPANIA VALUES(CANTIDAD, 0, TIPO, NOMBRE, JUEGO);
		END IF;
	END IF;
	WHILE NO_MORE_DATA = 0 DO -- SI SI EXISTEN BARCOS DEL TIPO SUMINISTRADO UBICADOS EN PUERTO ENTONCES SE HACE UN UPDATE SOBRE LA CANTIDAD DE BARCOS EXISTENTES
		IF CANTIDAD > 0 THEN -- SE SE ENVIA NUMERO DE BARCOS IGUAL A CERO ENTONCES NO SE INSERTA NADA
			UPDATE BARCOSXCOMPANIA SET CANTIDAD_BARCOS = NUMERO_BARCOS + CANTIDAD WHERE JUEGO_ID = JUEGO AND COMPANIA_NOMBRE = NOMBRE AND UBICACION_ID = 0 AND TIPO_BARCO_ID = TIPO;
		END IF;
		FETCH CURSOR_CANTIDAD_BARCOS INTO NUMERO_BARCOS;
	END WHILE;
	CLOSE CURSOR_CANTIDAD_BARCOS;
END $$
CREATE PROCEDURE INSERTAR_BARCOS_INICIALES(JUEGO INT)
BEGIN
   DECLARE NOMBRE_COMPANIA VARCHAR(15);
   DECLARE CONTADOR_TIPOS_BARCO, NO_MORE_COMPANIES, CONTADOR_BARCOS INT DEFAULT 0; -- LLEVA CUENTA DE LOS TIPOS DE BARCOS A INSERTAR
   DECLARE CURSOR_NOMBRES_COMPANIAS CURSOR FOR 
										SELECT NOMBRE 
										FROM   COMPANIA 
										WHERE  JUEGO_ID = JUEGO;
	DECLARE  CONTINUE HANDLER FOR NOT FOUND 
		SET  NO_MORE_COMPANIES = 1;
	OPEN CURSOR_NOMBRES_COMPANIAS;
	FETCH CURSOR_NOMBRES_COMPANIAS INTO NOMBRE_COMPANIA;
	WHILE NO_MORE_COMPANIES = 0 DO
		WHILE CONTADOR_TIPOS_BARCO < 3 DO
			CASE CONTADOR_TIPOS_BARCO
				WHEN 0 THEN 
					INSERT INTO BARCOSXCOMPANIA VALUES(3, 0, 1, NOMBRE_COMPANIA, JUEGO); -- DEPENDE DE CUANTOS BARCOS SE DEFINA
					INSERT INTO BARCOSXCOMPANIA VALUES(0, 1, 1, NOMBRE_COMPANIA, JUEGO); 
					INSERT INTO BARCOSXCOMPANIA VALUES(0, 2, 1, NOMBRE_COMPANIA, JUEGO); 
				WHEN 1 THEN 
					INSERT INTO BARCOSXCOMPANIA VALUES(3, 0, 2, NOMBRE_COMPANIA, JUEGO); -- DEPENDE DE CUANTOS BARCOS SE DEFINA
					INSERT INTO BARCOSXCOMPANIA VALUES(0, 1, 2, NOMBRE_COMPANIA, JUEGO); -- DEPENDE DE CUANTOS BARCOS SE DEFINA
					INSERT INTO BARCOSXCOMPANIA VALUES(0, 2, 2, NOMBRE_COMPANIA, JUEGO); -- DEPENDE DE CUANTOS BARCOS SE DEFINA
				WHEN 2 THEN 
					INSERT INTO BARCOSXCOMPANIA VALUES(3, 0, 3, NOMBRE_COMPANIA, JUEGO); -- DEPENDE DE CUANTOS BARCOS SE DEFINA
					INSERT INTO BARCOSXCOMPANIA VALUES(0, 1, 3, NOMBRE_COMPANIA, JUEGO); -- DEPENDE DE CUANTOS BARCOS SE DEFINA
					INSERT INTO BARCOSXCOMPANIA VALUES(0, 2, 3, NOMBRE_COMPANIA, JUEGO); -- DEPENDE DE CUANTOS BARCOS SE DEFINA
			END CASE;
			SET CONTADOR_TIPOS_BARCO = CONTADOR_TIPOS_BARCO + 1;
		END WHILE;
		FETCH CURSOR_NOMBRES_COMPANIAS INTO NOMBRE_COMPANIA;
		SET CONTADOR_TIPOS_BARCO = 0;
	END WHILE;
	CLOSE CURSOR_NOMBRES_COMPANIAS;
END $$
