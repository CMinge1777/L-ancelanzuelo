								UPDATE REPORTE SET CAPTURA_PARGO_MAR_PROFUNDO = CAPTURA_PARGO_MAR_PROFUNDO+CANTIDAD_PECES WHERE COMPANIA_NOMBRE = NOMBRE AND JUEGO_ID = JUEGO AND TURNO_ID = TURNO;
